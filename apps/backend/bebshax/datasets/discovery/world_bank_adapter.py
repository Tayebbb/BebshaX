"""World Bank Open Data adapter — live keyless API with illustrative fallback.

The live path fetches real Bangladesh indicator series from the free, keyless
World Bank API (https://api.worldbank.org/v2). When the network is unreachable
or the payload is malformed, the adapter falls back to the clearly-labeled
illustrative catalog so offline demos keep working. No exception escapes
``search()``.
"""

from __future__ import annotations

import asyncio
import csv
import io
import logging

import httpx

from bebshax.datasets.discovery.base_adapter import DatasetCandidateData, DatasetSourceAdapter
from bebshax.research.planner import DatasetRequirementSpec

logger = logging.getLogger(__name__)

SAMPLE_LICENSE = "Illustrative sample — generated by BebshaX for demonstration"
ILLUSTRATIVE_SOURCE_LABEL = "BebshaX Illustrative Catalog (modeled on World Bank Open Data)"

WORLD_BANK_API_BASE = "https://api.worldbank.org/v2"
LIVE_COUNTRY = "BGD"
LIVE_DATE_RANGE = "2015:2024"
LIVE_TIMEOUT_SECONDS = 6.0
LIVE_SOURCE_LABEL = "World Bank Open Data (live)"
LIVE_LICENSE = "CC BY-4.0 (World Bank Open Data terms of use)"
LIVE_LICENSE_URL = "https://datacatalog.worldbank.org/public-licenses"

# indicator code -> (display name, category, trigger keywords)
LIVE_INDICATORS: dict[str, tuple[str, str, tuple[str, ...]]] = {
    "FP.CPI.TOTL.ZG": (
        "Inflation, consumer prices (annual %)",
        "macro_prices",
        ("price", "cost", "inflation", "afford", "spend", "budget", "subscription"),
    ),
    "NY.GDP.PCAP.CD": (
        "GDP per capita (current US$)",
        "macro_income",
        ("income", "gdp", "purchasing", "afford", "economy", "revenue", "market"),
    ),
    "IT.NET.USER.ZS": (
        "Individuals using the Internet (% of population)",
        "digital_adoption",
        ("internet", "digital", "online", "app", "ecommerce", "e-commerce", "mobile", "tech", "software", "platform"),
    ),
    "SL.UEM.TOTL.ZS": (
        "Unemployment, total (% of total labor force)",
        "labor_market",
        ("employ", "job", "labor", "labour", "work", "student", "career"),
    ),
}


def live_indicator_url(code: str) -> str:
    """Real, keyless World Bank API URL for one Bangladesh indicator series."""
    return (
        f"{WORLD_BANK_API_BASE}/country/{LIVE_COUNTRY}/indicator/{code}"
        f"?format=json&per_page=100&date={LIVE_DATE_RANGE}"
    )


class WorldBankOpenDataAdapter(DatasetSourceAdapter):
    """World Bank Open Data source: live keyless API first, illustrative catalog offline."""

    def __init__(self, http_client: httpx.AsyncClient | None = None) -> None:
        # Injected client (tests use httpx.MockTransport); None -> real client per search.
        self._http_client = http_client

    @property
    def source_name(self) -> str:
        return "World Bank Open Data"

    async def search(
        self,
        queries: list[str],
        requirements: list[DatasetRequirementSpec],
    ) -> list[DatasetCandidateData]:
        combined_text = " ".join(queries).lower() + " " + " ".join(r.category + " " + r.description for r in requirements).lower()

        live_candidates = await self._search_live(combined_text)
        if live_candidates:
            return live_candidates

        logger.info("World Bank Open Data live API unavailable — serving illustrative fallback catalog")
        return self._illustrative_candidates(combined_text)

    # ── Live path ──────────────────────────────────────────────────────────

    async def _search_live(self, combined_text: str) -> list[DatasetCandidateData]:
        codes = self._select_indicators(combined_text)
        try:
            if self._http_client is not None:
                return await self._fetch_live_candidates(self._http_client, codes)
            async with httpx.AsyncClient(timeout=LIVE_TIMEOUT_SECONDS) as client:
                return await self._fetch_live_candidates(client, codes)
        except Exception as exc:  # offline venue: no network error may escape search()
            logger.debug("World Bank live fetch failed: %s", exc)
            return []

    @staticmethod
    def _select_indicators(combined_text: str) -> list[str]:
        matched = [code for code, (_, _, keywords) in LIVE_INDICATORS.items() if any(k in combined_text for k in keywords)]
        # Fewer than 2 topical matches -> serve the full macro-context set.
        return matched if len(matched) >= 2 else list(LIVE_INDICATORS)

    async def _fetch_live_candidates(
        self, client: httpx.AsyncClient, codes: list[str]
    ) -> list[DatasetCandidateData]:
        results = await asyncio.gather(
            *(self._fetch_indicator(client, code) for code in codes),
            return_exceptions=True,
        )
        candidates: list[DatasetCandidateData] = []
        for code, result in zip(codes, results):
            if isinstance(result, BaseException):
                logger.debug("World Bank indicator %s fetch failed: %s", code, result)
                continue
            if result is not None:
                candidates.append(result)
        return candidates

    async def _fetch_indicator(
        self, client: httpx.AsyncClient, code: str
    ) -> DatasetCandidateData | None:
        url = live_indicator_url(code)
        response = await client.get(url)
        response.raise_for_status()
        rows = self._parse_indicator_rows(response.json())
        if not rows:
            return None

        name, category, _ = LIVE_INDICATORS[code]
        csv_content = self._rows_to_csv(code, name, rows)
        years = [year for year, _ in rows]
        return DatasetCandidateData(
            source=LIVE_SOURCE_LABEL,
            external_id=f"worldbank-live-bgd-{code.lower().replace('.', '-')}",
            name=f"{name} — Bangladesh",
            description=(
                f"Official World Bank Open Data series {code} for Bangladesh, fetched live from the "
                f"free keyless api.worldbank.org API ({years[0]}–{years[-1]}, {len(rows)} annual observations)."
            ),
            url=url,
            download_url=url,
            publisher=LIVE_SOURCE_LABEL,
            license=LIVE_LICENSE,
            license_url=LIVE_LICENSE_URL,
            format="csv",
            size_bytes=len(csv_content.encode("utf-8")),
            sample_rows=len(rows),
            sample_columns=5,
            geographic_coverage="Bangladesh",
            population_coverage="National Population",
            relevant_variables=["year", "value", code],
            category=category,
            is_sample=False,
            raw_data_content=csv_content,
        )

    @staticmethod
    def _parse_indicator_rows(payload: object) -> list[tuple[str, float]]:
        """Extract (year, value) pairs from the World Bank [metadata, rows] envelope."""
        if not isinstance(payload, list) or len(payload) < 2 or not isinstance(payload[1], list):
            return []
        rows: list[tuple[str, float]] = []
        for entry in payload[1]:
            if not isinstance(entry, dict):
                continue
            value = entry.get("value")
            year = entry.get("date")
            if value is None or not isinstance(year, str) or not year:
                continue
            try:
                rows.append((year, float(value)))
            except (TypeError, ValueError):
                continue
        rows.sort(key=lambda pair: pair[0])
        return rows

    @staticmethod
    def _rows_to_csv(code: str, indicator_name: str, rows: list[tuple[str, float]]) -> str:
        buffer = io.StringIO()
        writer = csv.writer(buffer, lineterminator="\n")
        writer.writerow(["country", "indicator_code", "indicator_name", "year", "value"])
        for year, value in rows:
            writer.writerow(["Bangladesh", code, indicator_name, year, value])
        return buffer.getvalue()

    # ── Illustrative fallback (offline) ────────────────────────────────────

    def _illustrative_candidates(self, combined_text: str) -> list[DatasetCandidateData]:
        candidates: list[DatasetCandidateData] = []

        # 1. Global Findex — Bangladesh Mobile Financial Services (MFS) & Payment Adoption
        if any(w in combined_text for w in ["payment", "fintech", "wallet", "bkash", "nagad", "digital", "spend", "online", "money", "ecommerce"]):
            findex_csv = (
                "respondent_id,age,gender,has_mfs_account,monthly_digital_transactions,monthly_mfs_spend_bdt,uses_utility_pay,savings_frequency\n"
                + "\n".join(
                    f"FINDEX_BD_{2000 + i},{18 + (i % 35)},{'Female' if i % 2 == 0 else 'Male'},1,{8 + (i % 20)},{3500 + (i * 120)},{1 if i % 3 != 0 else 0},{'Regular' if i % 2 == 0 else 'Occasional'}"
                    for i in range(120)
                )
            )
            candidates.append(
                DatasetCandidateData(
                    source=ILLUSTRATIVE_SOURCE_LABEL,
                    external_id="worldbank-findex-bangladesh-mfs-2023",
                    name="Mobile Financial Inclusion & Payment Flows Sample — Bangladesh",
                    description="Illustrative sample modeled on financial-inclusion surveys such as the Global Findex: mobile wallet penetration (bKash/Nagad), monthly digital transaction volumes, peer-to-peer transfers, and digital payment readiness across demographic cohorts.",
                    url="https://catalog.bebshax.example/worldbank-findex-bangladesh-mfs-2023",
                    publisher="BebshaX Illustrative Catalog (modeled on the World Bank Global Findex)",
                    license=SAMPLE_LICENSE,
                    format="csv",
                    size_bytes=360000,
                    sample_rows=2500,
                    sample_columns=8,
                    geographic_coverage="Bangladesh",
                    population_coverage="Adult Population (18+)",
                    relevant_variables=["has_mfs_account", "monthly_digital_transactions", "monthly_mfs_spend_bdt"],
                    category="digital_payments",
                    is_sample=True,
                    raw_data_content=findex_csv,
                )
            )

        # 2. South Asia Enterprise Survey — Micro & SME Financial Health
        if any(w in combined_text for w in ["sme", "enterprise", "accounting", "business", "restaurant", "pos", "financial", "software"]):
            enterprise_csv = (
                "firm_id,sector,annual_sales_usd,operating_margin_pct,formal_bank_credit,software_budget_usd,digital_pos_adoption\n"
                + "\n".join(
                    f"WB_FIRM_{4000 + i},{'Food & Beverage Services' if i % 2 == 0 else 'Retail Trade'},{12000 + (i * 800)},{18.5 + (i % 12)},{1 if i % 3 == 0 else 0},{180 + (i * 15)},{1 if i % 2 == 0 else 0}"
                    for i in range(90)
                )
            )
            candidates.append(
                DatasetCandidateData(
                    source=ILLUSTRATIVE_SOURCE_LABEL,
                    external_id="worldbank-enterprise-survey-southasia-2023",
                    name="South Asia Small Business Finance & Tech Sample",
                    description="Illustrative sample modeled on enterprise surveys: firm-level financial constraints, operating margins, technology adoption, and digital POS tool investments among micro and small enterprises in South Asia.",
                    url="https://catalog.bebshax.example/worldbank-enterprise-survey-southasia-2023",
                    publisher="BebshaX Illustrative Catalog (modeled on World Bank Enterprise Surveys)",
                    license=SAMPLE_LICENSE,
                    format="csv",
                    size_bytes=490000,
                    sample_rows=1200,
                    sample_columns=7,
                    geographic_coverage="South Asia (Bangladesh Focus)",
                    population_coverage="Small & Medium Enterprise Operators",
                    relevant_variables=["operating_margin_pct", "software_budget_usd", "digital_pos_adoption"],
                    category="sme_finance",
                    is_sample=True,
                    raw_data_content=enterprise_csv,
                )
            )

        return candidates
